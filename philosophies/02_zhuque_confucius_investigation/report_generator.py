def generate_markdown_report(pipeline_result):
    """Generate structured Markdown report from pipeline results."""
    topic = pipeline_result.get("topic", "Unknown")
    phases = pipeline_result.get("phases", {})
    cg = pipeline_result.get("cognitive_graph", {})

    wood = phases.get("wood", {})
    fire = phases.get("fire", {})
    earth = phases.get("earth", {})
    metal = phases.get("metal", {})
    water = phases.get("water", {})

    seeds = wood.get("seeds", [])
    analysis = fire.get("analysis", "")
    synthesis = earth.get("synthesis", {})
    dims = metal.get("dimensions", {})
    agent_eval = metal.get("agent_eval", {})
    new_seeds = water.get("new_seeds", [])

    context = "Topic: {}\n\nWOOD SEEDS ({}):\n{}\n\nFIRE ANALYSIS ({} chars):\n{}\n\nEARTH SYNTHESIS:\nSummary: {}\nFindings: {}\nRecommendations: {}\nData Gaps: {}\n\nMETAL VALIDATION:\nVerdict: {} (Score: {:.2f})\nDimensions: {}\nAgent Grade: {}/{} ({}/10)\n\nCOGNITIVE GRAPH:\nResiduals: {}, Patterns: {}\nPath Weights: {}\nEvolution: {}\n\nWATER SEEDS ({}):\n{}".format(
        topic,
        len(seeds),
        json.dumps([s.get('angle','') for s in seeds[:5]], ensure_ascii=False, indent=2),
        len(analysis),
        analysis[:1500],
        synthesis.get('executive_summary', 'N/A'),
        json.dumps(synthesis.get('key_findings', [])[:5], ensure_ascii=False),
        json.dumps(synthesis.get('recommendations', [])[:5], ensure_ascii=False),
        json.dumps(synthesis.get('data_gaps', [])[:5], ensure_ascii=False),
        metal.get('verdict', 'N/A'),
        metal.get('composite_score', 0),
        json.dumps(dims, indent=2),
        agent_eval.get('grade', 'N/A'),
        agent_eval.get('grade_label', 'N/A'),
        agent_eval.get('overall_score', 0),
        cg.get('residuals', 0),
        cg.get('patterns', 0),
        json.dumps(cg.get('path_weights', {}).get('updated', {}), indent=2),
        json.dumps(cg.get('evolution', {}).get('lessons_learned', []), ensure_ascii=False),
        len(new_seeds),
        json.dumps([s.get('angle','')[:80] for s in new_seeds[:5]], ensure_ascii=False),
    )

    verdict_str = metal.get('verdict', '?')
    score_str = "{:.2f}".format(metal.get('composite_score', 0))
    grade_str = agent_eval.get('grade', '?')
    ts_str = time.strftime('%Y-%m-%d %H:%M')

    prompt = (
        "You are the Zhuque Report Engine of SkyCetus. Generate a comprehensive research report.\n\n"
        + context + "\n\n"
        "Generate a Markdown report with this structure:\n"
        "# [topic] - Wuxing Analysis Report\n\n"
        "## Executive Summary\n"
        "(3 sentences: core finding, market insight, strategic implication)\n\n"
        "## Key Findings\n"
        "(5-7 bullet points, each with data support)\n\n"
        "## Deep Analysis\n"
        "### Market Landscape\n"
        "### Technology Trends\n"
        "### Competition\n\n"
        "## Risk Assessment\n"
        "(3-4 risks with severity and mitigation)\n\n"
        "## Strategic Recommendations\n"
        "(3-5 actionable recommendations with priority P0/P1/P2)\n\n"
        "## Cognitive Evolution\n"
        "(Patterns, path weight shifts, residuals from cognitive graph)\n\n"
        "## Next Research Directions\n"
        "(Water seeds for next cycle)\n\n"
        "---\n"
        "*Generated by LongZhu Engine Wuxing Pipeline v4.1 | Metal: " + verdict_str + " (" + score_str + ") | Grade: " + grade_str + " | " + ts_str + "*\n\n"
        "Requirements:\n"
        "- Write in Chinese for maximum impact\n"
        "- Include specific numbers and data points\n"
        "- Keep total length 1500-2500 chars\n"
        "- Be actionable and decision-ready\n"
        "- Output ONLY Markdown, no code fences"
    )

    if LLM:
        result = call_llm(prompt, model="minimax", timeout=60, thinking_budget=500)
        if result:
            if result.strip().startswith('```'):
                lines = result.strip().split('\n')
                if lines[0].startswith('```'):
                    lines = lines[1:]
                if lines and lines[-1].strip() == '```':
                    lines = lines[:-1]
                result = '\n'.join(lines)
            return result

    return _fallback_markdown(topic, synthesis, metal, agent_eval, cg, new_seeds)


def _fallback_markdown(topic, synthesis, metal, agent_eval, cg, new_seeds):
    """Fallback Markdown when LLM is unavailable."""
    findings = synthesis.get("key_findings", [])
    recs = synthesis.get("recommendations", [])

    md = "# {} - Wuxing Analysis Report\n\n".format(topic)
    md += "## Executive Summary\n{}\n\n".format(synthesis.get('executive_summary', 'Analysis pending.'))

    md += "## Key Findings\n"
    for f in findings[:7]:
        if isinstance(f, dict):
            md += "- **[{}]** {}\n".format(f.get('confidence','?'), f.get('finding',''))
        else:
            md += "- {}\n".format(f)

    md += "\n## Validation\n"
    md += "- **Metal**: {} (Score: {:.2f})\n".format(metal.get('verdict',''), metal.get('composite_score',0))
    md += "- **Agent Grade**: {} ({}/10)\n".format(agent_eval.get('grade','?'), agent_eval.get('overall_score',0))

    md += "\n## Recommendations\n"
    for r in recs[:5]:
        if isinstance(r, dict):
            md += "- **[{}]** {}\n".format(r.get('priority','?'), r.get('action',''))
        else:
            md += "- {}\n".format(r)

    md += "\n## Next Research Directions\n"
    for s in new_seeds[:5]:
        md += "- [{}] {}\n".format(s.get('priority','?'), s.get('angle','')[:100])

    md += "\n---\n*LongZhu Engine | {}*\n".format(time.strftime('%Y-%m-%d %H:%M'))
    return md


def generate_html_report(topic, markdown_report, pipeline_result):
    """Generate interactive HTML dashboard."""
    metal = pipeline_result.get("phases", {}).get("metal", {})
    agent_eval = metal.get("agent_eval", {})
    cg = pipeline_result.get("cognitive_graph", {})
    dims = metal.get("dimensions", {})
    elapsed = pipeline_result.get("total_elapsed", 0)
    lux = pipeline_result.get("lux_distribution", {})
    total_lux = lux.get("total_lux", lux.get("total_distributed", 0)) if lux else 0

    NL = chr(10)

    # Build dimension bars
    dim_bars = ""
    for k, v in dims.items():
        pct = int(v * 100) if isinstance(v, (int, float)) else 50
        color = "#22c55e" if pct >= 70 else "#eab308" if pct >= 40 else "#ef4444"
        label = k.replace("_", " ").title()
        dim_bars += '<div class="dim-row"><span class="dim-label">{}</span><div class="dim-bar"><div class="dim-fill" style="width:{}%;background:{}"></div></div><span class="dim-val">{}%</span></div>{}'.format(label, pct, color, pct, NL)

    # Agent scores
    agent_cards = ""
    for a in agent_eval.get("agents", []):
        score = a.get("score", 0)
        color = "#22c55e" if score >= 7 else "#eab308" if score >= 5 else "#ef4444"
        name = a.get("agent", "?").title()
        agent_cards += '<div class="agent-card"><div class="agent-name">{}</div><div class="agent-score" style="color:{}">{}</div></div>{}'.format(name, color, score, NL)

    # Path weights
    pw = cg.get("path_weights", {}).get("updated", {})
    pw_a = pw.get("A", 65)
    pw_b = pw.get("B", 25)
    pw_c = pw.get("C", 10)

    verdict = metal.get("verdict", "?")
    verdict_color = "#22c55e" if verdict == "PASS" else "#eab308" if verdict == "CONDITIONAL" else "#ef4444"
    grade = agent_eval.get("grade", "?")
    grade_color = "#22c55e" if grade in ("S","A") else "#eab308" if grade == "B" else "#ef4444"

