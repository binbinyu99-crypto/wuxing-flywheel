def generate_report(pipeline_result, deploy=False, deploy_path=None):
    """Full report generation pipeline."""
    topic = pipeline_result.get("topic", "Unknown")
    t0 = time.time()

    print("[Zhuque] Generating Markdown report...")
    markdown = generate_markdown_report(pipeline_result)
    t_md = time.time() - t0
    print("[Zhuque] Markdown: {} chars ({:.1f}s)".format(len(markdown), t_md))

    t1 = time.time()
    html = generate_html_report(topic, markdown, pipeline_result)
    t_html = time.time() - t1
    print("[Zhuque] HTML: {} chars ({:.1f}s)".format(len(html), t_html))

    metal = pipeline_result.get("phases", {}).get("metal", {})
    agent_eval = metal.get("agent_eval", {})
    cg = pipeline_result.get("cognitive_graph", {})

    json_summary = {
        "topic": topic,
        "generated_at": time.strftime("%Y-%m-%dT%H:%M:%S+08:00"),
        "pipeline_version": pipeline_result.get("pipeline_version", "?"),
        "total_elapsed": pipeline_result.get("total_elapsed", 0),
        "metal_verdict": metal.get("verdict", "?"),
        "metal_score": metal.get("composite_score", 0),
        "agent_grade": agent_eval.get("grade", "?"),
        "agent_score": agent_eval.get("overall_score", 0),
        "cg_residuals": cg.get("residuals", 0),
        "cg_patterns": cg.get("patterns", 0),
        "water_seeds": len(pipeline_result.get("phases", {}).get("water", {}).get("new_seeds", [])),
        "lux": pipeline_result.get("lux_distribution", {}).get("total_lux", 0),
    }

    report_dir = deploy_path or r"D:\ClawMatrix\reports"
    os.makedirs(report_dir, exist_ok=True)

    slug = re.sub(r'[^a-z0-9]+', '-', topic.lower())[:40].strip('-')
    ts = time.strftime("%Y%m%d_%H%M")

    md_path = os.path.join(report_dir, "{}_{}.md".format(slug, ts))
    html_path = os.path.join(report_dir, "{}_{}.html".format(slug, ts))
    json_path = os.path.join(report_dir, "{}_{}.json".format(slug, ts))

    with open(md_path, 'w', encoding='utf-8') as f:
        f.write(markdown)
    with open(html_path, 'w', encoding='utf-8') as f:
        f.write(html)
    with open(json_path, 'w', encoding='utf-8') as f:
        json.dump(json_summary, f, ensure_ascii=False, indent=2)

    total = time.time() - t0
    print("[Zhuque] Reports saved to {}/ ({:.1f}s total)".format(report_dir, total))

    return {
        "markdown": markdown,
        "html_length": len(html),
        "json_summary": json_summary,
        "files": {"md": md_path, "html": html_path, "json": json_path},
        "timing": {"markdown": t_md, "html": t_html, "total": total},
    }


